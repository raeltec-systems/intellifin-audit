SIX_KEYS = {
    "allowed_origins",
    "attribute_label_patterns",
    "credential_ref",
    "kind",
    "permitted_actions",
    "secondary_key",
}


def main() -> int:
    vectors = []
    for name, note, digest_input, envelope in VECTORS:
        if set(envelope) != SIX_KEYS:
            raise SystemExit(f"{name}: envelope must hold exactly the six AD-2 keys")
        canonical = rfc8785.dumps(envelope)
        vectors.append(
            {
                "name": name,
                "note": note,
                "input": digest_input,
                "envelope": envelope,
                "canonicalText": canonical.decode("utf-8"),
                "digest": hashlib.sha256(canonical).hexdigest(),
            }
        )

    digests = [vector["digest"] for vector in vectors]
    if len(set(digests)) != len(digests):
        raise SystemExit("two vectors share a digest; the fixture would prove nothing")

    fixture = {
        "producer": f"Python {sys.version.split()[0]} + rfc8785 0.1.4 + hashlib.sha256",
        "producedBy": "scripts/make-registration-digest-golden.py",
        "regenerateWith": "uv run scripts/make-registration-digest-golden.py",
        "why": (
            "AD-2 digest vectors, produced by an implementation that is NOT the code "
            "under test. packages/domain/src/registrations/target-system.ts is checked "
            "against these bytes; a fixture produced by that module would prove only "
            "that it equals itself. The envelopes in the generator are written out by "
            "hand, so the projection from a registration to its six hashed keys is "
            "checked too, not just the hash of an envelope this repository derived."
        ),
        "algorithm": (
            "digest = SHA-256( RFC 8785 canonical JSON of the six-key envelope ), "
            "lower-case hex. No previous-hash prefix: that belongs to the audit chain, "
            "not to this digest."
        ),
        "vectors": vectors,
    }
    OUT.write_text(json.dumps(fixture, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(vectors)} vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
