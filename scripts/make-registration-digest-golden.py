"""Produce tests/fixtures/registration-digest-golden.json.

The point of this script is that it is NOT TypeScript. `packages/domain/src/registrations/
target-system.ts` computes the AD-2 registration digest, and a fixture generated by that
code would only prove the code equals itself. Everything here — the six-key envelope, the
RFC 8785 canonical bytes, and the SHA-256 — is produced by an independent implementation:
`rfc8785` from PyPI and the standard library's `hashlib`.

The envelopes below are written out BY HAND rather than derived from the inputs by a
Python copy of the projection rule. That is deliberate: the projection (which key holds
what, and how the sets are normalized) is exactly the part a shared helper would stop
checking. A reviewer can read each `envelope` and see that it is the six keys AD-2 names.

Run it from the repository root:

    uv run scripts/make-registration-digest-golden.py
"""

