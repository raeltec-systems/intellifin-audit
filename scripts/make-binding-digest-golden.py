"""Produce tests/fixtures/binding-digest-golden.json.

The point of this script is that it is NOT TypeScript. `packages/domain/src/sources/
population-source.ts` computes the Population Source binding digest, and a fixture
generated by that code would only prove the code equals itself. Everything here — the
five-key envelope, the RFC 8785 canonical bytes, and the SHA-256 — is produced by an
independent implementation: `rfc8785` from PyPI and the standard library's `hashlib`.

The envelopes below are written out BY HAND rather than derived from the inputs by a
Python copy of the projection rule. That is deliberate: the projection (which key holds
what, which member is a list and which is a set) is exactly the part a shared helper
would stop checking. A reviewer can read each `envelope` and see the five keys.

The two normalization rules are opposite on purpose and each has a vector that fails if
they are swapped:

  * `declared_schema` is an ORDERED list — a schema declares field positions, and
    `[account, amount]` is not the same declaration as `[amount, account]`. Duplicates
    are removed and blanks dropped, but the typed order is hashed.
  * `sensitive_fields` is a SET — sorted by UTF-16 code unit — because masking asks only
    whether a field is in the group.

Run it from the repository root:

    uv run scripts/make-binding-digest-golden.py
"""

