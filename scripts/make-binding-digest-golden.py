FIVE_KEYS = {
    "declared_count_mechanism",
    "declared_schema",
    "kind",
    "location",
    "sensitive_fields",
}


def main() -> int:
    vectors = []
    for name, note, digest_input, envelope in VECTORS:
        if set(envelope) != FIVE_KEYS:
            raise SystemExit(f"{name}: envelope must hold exactly the five binding keys")
        for field in envelope["sensitive_fields"]:
            if field not in envelope["declared_schema"]:
                raise SystemExit(f"{name}: a sensitive field must be in the declared schema")
        canonical = rfc8785.dumps(envelope)
        vectors.append(
            {
                "name": name,
                "note": note,
                "input": digest_input,
                "envelope": envelope,
                "canonicalText": canonical.decode("utf-8"),
                "digest": hashlib.sha256(canonical).hexdigest(),
            }
        )

    # Two vectors deliberately SHARE a digest — the set-vs-list pair — so the check is
    # that every DISTINCT envelope has a distinct digest, and that the pair that must
    # agree does.
    by_envelope: dict[str, str] = {}
    for vector in vectors:
        key = json.dumps(vector["envelope"], sort_keys=True, ensure_ascii=False)
        seen = by_envelope.setdefault(key, vector["digest"])
        if seen != vector["digest"]:
            raise SystemExit("one envelope produced two digests")
    if len({v["digest"] for v in vectors}) != len(by_envelope):
        raise SystemExit("two different envelopes share a digest; the fixture would prove nothing")

    fixture = {
        "producer": f"Python {sys.version.split()[0]} + rfc8785 0.1.4 + hashlib.sha256",
        "producedBy": "scripts/make-binding-digest-golden.py",
        "regenerateWith": "uv run scripts/make-binding-digest-golden.py",
        "why": (
            "Population Source binding digest vectors, produced by an implementation "
            "that is NOT the code under test. packages/domain/src/sources/"
            "population-source.ts is checked against these bytes; a fixture produced by "
            "that module would prove only that it equals itself. The envelopes in the "
            "generator are written out by hand, so the projection from a binding to its "
            "five hashed keys is checked too, not just the hash of an envelope this "
            "repository derived."
        ),
        "algorithm": (
            "digest = SHA-256( RFC 8785 canonical JSON of the five-key envelope "
            "{declared_count_mechanism, declared_schema, kind, location, "
            "sensitive_fields} ), lower-case hex. declared_schema keeps its typed "
            "order; sensitive_fields is sorted by UTF-16 code unit."
        ),
        "vectors": vectors,
    }
    OUT.write_text(json.dumps(fixture, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(vectors)} vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
