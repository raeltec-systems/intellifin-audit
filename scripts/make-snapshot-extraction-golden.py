def main() -> int:
    cells = []
    for name, snapshot, locator in CELLS:
        found = cell(BY_NAME[snapshot], locator)
        cells.append(
            {
                "name": name,
                "snapshot": snapshot,
                "locator": locator,
                "resolves": found is not None,
                "value": None if found is None else found["value"],
                "label": None if found is None else found["label"],
            }
        )
    attributes = []
    for name, snapshot, value in ATTRIBUTES:
        corroboration, failure = judge(BY_NAME[snapshot], value)
        attributes.append(
            {
                "name": name,
                "snapshot": snapshot,
                "attribute": value,
                "corroboration": corroboration,
                "failure": failure,
            }
        )
    OUT.write_text(
        json.dumps(
            {
                "producer": f"Python {sys.version.split()[0]} + rfc8785 {rfc8785.__version__ if hasattr(rfc8785, '__version__') else '0.1.4'} + csv + json",
                "producedBy": "scripts/make-snapshot-extraction-golden.py",
                "regenerateWith": "uv run scripts/make-snapshot-extraction-golden.py",
                "why": (
                    "Structural Snapshot extraction vectors, produced by an implementation that is NOT "
                    "the code under test. packages/domain/src/runs/structural-snapshot.ts is checked "
                    "against these cells and verdicts; a fixture produced by that module would prove "
                    "only that it equals itself, which is no evidence at all for an extractor whose "
                    "whole job is to be a second opinion on what an adapter asserted."
                ),
                "grammar": (
                    "A locator is $.<collection>[<index>].<field>, anchored, with no '.', '[' or ']' "
                    "inside either name and no leading zero on the index. For a sheet the collection "
                    "segment is exactly 'rows', the index is the 0-based DATA row after the header and "
                    "after a leading '# SYNTHETIC' marker line, and the label is the header cell. For "
                    "json the collection is an envelope key holding a list of objects, the index is the "
                    "0-based position in it, and the label is the property key."
                ),
                "matching": (
                    "An attribute is matched only when the locator resolves, the re-read label equals "
                    "the declared label, the re-read value equals originalValue as RFC 8785 canonical "
                    "bytes, the grounding's extractedText is the text of that value, and normalizedValue "
                    "is either that value or its UTC normalization. Anything else is contradictory, and "
                    "nothing is ever repaired by preferring one side."
                ),
                "snapshots": SNAPSHOTS,
                "cells": cells,
                "attributes": attributes,
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cells)} cells, {len(attributes)} attributes")
    return 0


