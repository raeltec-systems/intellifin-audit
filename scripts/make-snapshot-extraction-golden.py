"""Produce tests/fixtures/snapshot-extraction-golden.json.

The point of this script is that it is NOT TypeScript.
`packages/domain/src/runs/structural-snapshot.ts` re-reads a stored Structural Snapshot
and says whether an Observation's attribute is `matched` or `contradictory`; a fixture
generated by that module would prove only that it equals itself, which is precisely no
evidence at all for an extractor whose whole job is to be a second opinion.

Everything below is an independent implementation:

  * the locator grammar `$.<collection>[<index>].<field>`, parsed by a regex written here;
  * the `sheet` read — Python's own `csv` module, the `# SYNTHETIC` marker line dropped,
    the header row taken as the label rule;
  * the `json` read — Python's `json`, the collection taken from the envelope, the
    property key taken as the label rule;
  * the value comparison — `rfc8785` from PyPI, the same canonicalization the TypeScript
    uses and a different implementation of it;
  * the UTC normalization — `datetime`, which refuses an impossible calendar date rather
    than rolling it over the way `Date.parse` does.

The `sheet` snapshot is the REAL `fixtures/northstar/generated/role-matrix.csv`, read off
disk and embedded verbatim, so the vectors are taken over bytes a synthetic Target System
actually serves — including the leading `entry` ordinal that keeps two conflicting policy
entries for one role distinguishable.

Run it from the repository root:

    uv run scripts/make-snapshot-extraction-golden.py
"""

from __future__ import annotations

