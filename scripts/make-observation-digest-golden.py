def corroborated(record: dict, verdict: str) -> dict:
    """The same record after the Evidence Quality Gate judged its attributes."""
    copy = json.loads(json.dumps(record))
    copy["identity"]["corroboration"] = verdict
    for attribute in copy["attributes"]:
        attribute["corroboration"] = verdict
    return copy


def corroborated_envelope(envelope: dict, verdict: str) -> dict:
    copy = json.loads(json.dumps(envelope))
    copy["identity"]["corroboration"] = verdict
    for attribute in copy["attributes"]:
        attribute["corroboration"] = verdict
    return copy


