# The batch digest, over the ordered list of per-Observation digests. It is what detects
# a removed row, a reordered batch or an edited stored digest — none of which a per-row
# digest can see, because each surviving row still agrees with itself.
BATCHES: list[tuple[str, str, list[str]]] = [
    ("empty", "No Observations registered. A digest over the empty list.", []),
    (
        "three-in-order",
        "The first three vectors in registration order.",
        ["found-grounded-identity", "absent-no-identity", "ambiguous-no-identity"],
    ),
    (
        "three-reordered",
        "The same three digests in a different order. Its batch digest must DIFFER: "
        "order is part of what the event records.",
        ["absent-no-identity", "found-grounded-identity", "ambiguous-no-identity"],
    ),
]


def main() -> int:
    vectors = []
    for name, note, record, envelope in VECTORS:
        if set(envelope) != THIRTEEN_KEYS:
            raise SystemExit(f"{name}: envelope must hold exactly the thirteen wire keys")
        if (envelope["found"] == "true") != (envelope["identity"] is not None):
            raise SystemExit(f"{name}: a grounded identity is required exactly when found is true")
        canonical = rfc8785.dumps(envelope)
        vectors.append(
            {
                "name": name,
                "note": note,
                "record": record,
                "envelope": envelope,
                "canonicalText": canonical.decode("utf-8"),
                "digest": hashlib.sha256(canonical).hexdigest(),
            }
        )

    by_name = {vector["name"]: vector["digest"] for vector in vectors}
    # Every distinct envelope must have a distinct digest, or a vector proves nothing.
    if len({vector["digest"] for vector in vectors}) != len(vectors):
        raise SystemExit("two different envelopes share a digest; the fixture would prove nothing")

    batches = []
    for name, note, members in BATCHES:
        digests = [by_name[member] for member in members]
        canonical = rfc8785.dumps(digests)
        batches.append(
            {
                "name": name,
                "note": note,
                "members": members,
                "digests": digests,
                "canonicalText": canonical.decode("utf-8"),
                "batchDigest": hashlib.sha256(canonical).hexdigest(),
            }
        )
    if batches[1]["batchDigest"] == batches[2]["batchDigest"]:
        raise SystemExit("a reordered batch produced the same digest; order is not hashed")

    fixture = {
        "producer": f"Python {sys.version.split()[0]} + rfc8785 0.1.4 + hashlib.sha256",
        "producedBy": "scripts/make-observation-digest-golden.py",
        "regenerateWith": "uv run scripts/make-observation-digest-golden.py",
        "why": (
            "Observation digest vectors, produced by an implementation that is NOT the "
            "code under test. packages/domain/src/runs/observation.ts is checked "
            "against these bytes; a fixture produced by that module would prove only "
            "that it equals itself. The envelopes in the generator are written out by "
            "hand, so the projection from a wire record to its thirteen hashed keys is "
            "checked too, not just the hash of an envelope this repository derived."
        ),
        "algorithm": (
            "digest = SHA-256( RFC 8785 canonical JSON of the thirteen-key envelope "
            "{attributes, capture_method, evidence_ids, found, identity, match_origin, "
            "observation_id, observed_at, population_record_key, schema_version, "
            "step_execution_id, target_system, work_item_id} ), lower-case hex. "
            "Attributes keep their declared order. No operational field — attempt, "
            "lease, revision, row version, coverage, registration time — is in the "
            "envelope. batchDigest = SHA-256( RFC 8785 canonical JSON of the ordered "
            "list of per-Observation digests )."
        ),
        "vectors": vectors,
        "batches": batches,
    }
    OUT.write_text(json.dumps(fixture, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(vectors)} vectors and {len(batches)} batches")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
