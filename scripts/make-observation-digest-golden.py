"""Produce tests/fixtures/observation-digest-golden.json.

The point of this script is that it is NOT TypeScript. `packages/domain/src/runs/
observation.ts` computes the Observation digest, and a fixture generated by that code
would only prove the code equals itself. Everything here — the thirteen-key envelope,
the RFC 8785 canonical bytes and the SHA-256 — is produced by an independent
implementation: `rfc8785` from PyPI and the standard library's `hashlib`.

The envelopes below are written out BY HAND rather than derived from the wire record by
a Python copy of the projection rule. That is deliberate: the projection (which wire key
becomes which snake_case envelope key, and which fields are deliberately absent) is
exactly the part a shared helper would stop checking. A reviewer can read each
`envelope` and see the thirteen keys.

What the digest covers and what it must not:

  * it covers the WIRE RECORD, all thirteen §B.1 keys including `observationId`,
    every attribute's grounding and every attribute's corroboration;
  * it covers NOTHING operational. There is no attempt counter, lease, revision, row
    version, coverage state or registration time in the envelope, because those change
    for reasons that have nothing to do with what was observed, and a digest that moved
    with them would make an untouched row look tampered with.

Run it from the repository root:

    uv run scripts/make-observation-digest-golden.py
"""

